#!/usr/bin/env bash
################################################################################
# COGNITO OAUTH TOKEN GENERATOR SCRIPT (get_token.sh)
# ------------------------------------------------------------------------------
# Why do we need this script?
# Our public AI endpoint (API Gateway) is locked behind AWS Cognito security.
# Before you can send prompts to Llama-3.1-8B using `curl`, Python, or the
# OpenAI SDK, you must exchange your credentials for a temporary digital pass
# (a JWT token).
#
# How this script is meant to be run:
#   eval "$(./scripts/get_token.sh user)"   # Log in as the human demo user
#   eval "$(./scripts/get_token.sh m2m)"    # Log in as an automated backend app
#
# Why `eval "$(...)"`?
# Instead of running commands directly, this script prints `export ...` lines
# to your terminal. Wrapping it in `eval "$(...)"` injects `OPENAI_API_BASE`
# and `OPENAI_API_KEY` straight into your active shell environment so any
# OpenAI-compatible client immediately picks them up!
################################################################################

# Strict Bash Safety Flags ("Fail Fast"):
# - `set -e`: Stop immediately if any command fails.
# - `set -u`: Error out if a required variable is missing.
# - `set -o pipefail`: Catch errors inside piped (`|`) commands like `curl | jq`.
set -euo pipefail

# ------------------------------------------------------------------------------
# Step 1: Parse Login Mode & Locate Terraform Outputs
# ------------------------------------------------------------------------------
# Read the first command-line argument ("user" or "m2m"). Defaults to "user".
MODE="${1:-user}"

# Resolve the paths to `scripts/` and `terraform/` regardless of where you run this from
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
TF_DIR="$(dirname "$SCRIPT_DIR")/terraform"

# Ask Terraform for the live public API Gateway URL (ending in `/v1`)
API_BASE=$(terraform -chdir="$TF_DIR" output -raw openai_api_base_url)
AWS_REGION="${AWS_DEFAULT_REGION:-us-east-1}"

# ------------------------------------------------------------------------------
# Step 2: Authenticate with AWS Cognito (Two Supported Modes)
# ------------------------------------------------------------------------------
if [[ "$MODE" == "user" ]]; then
  # ============================================================================
  # MODE A: Human User Login (`USER_PASSWORD_AUTH`)
  # Simulates a person logging in with an email address and password.
  # ============================================================================

  # Verify the demo user's email and password were loaded from `.env`
  # Note: Error messages are printed as `echo '...' >&2; exit 1` so that if
  # the user ran `eval "$(./scripts/get_token.sh)"`, the outer shell also exits cleanly.
  if [[ -z "${TF_VAR_demo_user_email:-}" || -z "${TF_VAR_demo_user_password:-}" ]]; then
    echo "echo 'Error: TF_VAR_demo_user_email and TF_VAR_demo_user_password must be set in .env' >&2; exit 1"
    exit 1
  fi

  # Fetch the public User App Client ID generated by Terraform
  USER_CLIENT_ID=$(terraform -chdir="$TF_DIR" output -raw cognito_user_client_id)

  # Send a POST request to AWS Cognito's authentication API with the email & password,
  # then parse out the resulting `IdToken` (JWT) using `jq`.
  TOKEN=$(curl -s -X POST "https://cognito-idp.${AWS_REGION}.amazonaws.com/" \
    -H "Content-Type: application/x-amz-json-1.1" \
    -H "X-Amz-Target: AWSCognitoIdentityProviderService.InitiateAuth" \
    -d "{
      \"AuthFlow\": \"USER_PASSWORD_AUTH\",
      \"ClientId\": \"${USER_CLIENT_ID}\",
      \"AuthParameters\": {
        \"USERNAME\": \"${TF_VAR_demo_user_email}\",
        \"PASSWORD\": \"${TF_VAR_demo_user_password}\"
      }
    }" | jq -r '.AuthenticationResult.IdToken')

elif [[ "$MODE" == "m2m" ]]; then
  # ============================================================================
  # MODE B: Machine-to-Machine Login (`client_credentials` OAuth 2.0 Flow)
  # Used by automated scripts, microservices, or CI/CD pipelines that authenticate
  # using a Client ID + Client Secret without a human email/password.
  # ============================================================================

  # Retrieve the M2M Client ID, Client Secret, and Cognito `/oauth2/token` URL
  M2M_CLIENT_ID=$(terraform -chdir="$TF_DIR" output -raw cognito_m2m_client_id)
  M2M_SECRET=$(terraform -chdir="$TF_DIR" output -raw cognito_m2m_client_secret)
  TOKEN_ENDPOINT=$(terraform -chdir="$TF_DIR" output -raw cognito_oauth_token_endpoint)

  # Send an HTTP Basic Auth (`-u id:secret`) request to Cognito's OAuth token
  # endpoint and extract the `access_token` (JWT) using `jq`.
  TOKEN=$(curl -s -X POST "${TOKEN_ENDPOINT}" \
    -u "${M2M_CLIENT_ID}:${M2M_SECRET}" \
    -H "Content-Type: application/x-www-form-urlencoded" \
    -d "grant_type=client_credentials" | jq -r '.access_token')

else
  # Invalid argument passed (anything other than "user" or "m2m")
  echo "echo 'Usage: eval \"\$(./scripts/get_token.sh [user|m2m])\"' >&2; exit 1"
  exit 1
fi

# ------------------------------------------------------------------------------
# Step 3: Validate Token Retrieval
# ------------------------------------------------------------------------------
# If Cognito rejected the login (e.g., wrong password or uninitialized cluster),
# `jq` returns an empty string or `"null"`. Catch that here before exporting bad variables.
if [[ -z "$TOKEN" || "$TOKEN" == "null" ]]; then
  echo "echo 'Failed to retrieve authentication token from Cognito.' >&2; exit 1"
  exit 1
fi

# ------------------------------------------------------------------------------
# Step 4: Output Shell Export Commands for `eval`
# ------------------------------------------------------------------------------
# Prints standard OpenAI environment variables (`OPENAI_API_BASE` and
# `OPENAI_API_KEY`) so your terminal session is immediately authenticated.
echo "export OPENAI_API_BASE=\"${API_BASE}\""
echo "export OPENAI_API_KEY=\"${TOKEN}\""
echo "echo 'Authenticated (${MODE} mode). Token prefix: ${TOKEN:0:20}...'"